async function migrate() {
  console.log('Iniciando migração do catálogo para o Cloud Firestore (confloraai)...');
  const keyPath = path.resolve(process.cwd(), 'firebase-service-account.json');

  const firestore = new Firestore({
    projectId: 'confloraai',
    keyFilename: keyPath,
  });

  const batch = firestore.batch();
  const now = new Date().toISOString();

  for (const item of INITIAL_CATALOG) {
    const docRef = firestore.collection('products').doc(item.id);
    batch.set(docRef, {
      ...item,
      created_at: now,
      updated_at: now,
    }, { merge: true });
    console.log(`✓ Preparado: [${item.id}] ${item.descricao} - Estoque: ${item.stockQuantity}`);
  }

  await batch.commit();
  console.log(`\n🎉 SUCESSO! ${INITIAL_CATALOG.length} produtos migrados para a coleção "products" no Firestore.`);
  process.exit(0);
}

if (require.main === module) {
  migrate().catch((err) => {
    console.error('Falha na migração:', err);
    process.exit(1);
  });
}

module.exports = {
  migrate,
  INITIAL_CATALOG,
};
